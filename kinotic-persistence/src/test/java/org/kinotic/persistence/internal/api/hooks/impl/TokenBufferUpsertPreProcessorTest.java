/**
 * Pins what the upsert pre-processing does to an entity on its way to Elasticsearch: which fields it reads,
 * rewrites, adds and drops, what it extracts into the {@link EntityHolder}, and what it rejects. Every
 * collaborator is the real one, so a replacement of the processing must pass this unchanged.
 */
public class TokenBufferUpsertPreProcessorTest {

    private static final String ORG = "org1";
    private static final String APP = "app1";
    private static final ScopedParticipant TENANT1 = applicationParticipant("tenant1");
    private static final ScopedParticipant ORGANIZATION =
            new DefaultOrganizationParticipant("admin",
                                               ORG,
                                               Map.of(ParticipantConstants.PARTICIPANT_TYPE_METADATA_KEY,
                                                      ParticipantConstants.PARTICIPANT_TYPE_USER),
                                               List.of("ADMIN"));

    private final JsonMapper jsonMapper = JsonMapper.builder().build();
    private final DomainPersistenceProperties properties = new DomainPersistenceProperties();

    @Test
    public void idIsExtractedAndTheDataPassesThroughUnchanged() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.NONE),
                                                            Map.of("id", new IdDecorator()));
        String input = """
                {"id":"car-1","make":"Audi","year":2020,"tags":["a","b"],
                 "owner":{"id":"person-9","name":"Ann","addresses":[{"street":"1 Main","zip":"87101"},{"street":"2 Oak","zip":"87102"}]},
                 "empty":{},"none":null}""";

        EntityHolder<RawJson> holder = process(processor, input, context(TENANT1));

        assertEquals(json(input), json(holder.entity()), "Every field is persisted as given, at every depth");
        assertEquals("car-1", holder.id());
        assertEquals("car-1", holder.getDocumentId(), "Without tenancy the document id is the entity id");
        assertNull(holder.tenantId());
        assertNull(holder.version());
        assertFalse(holder.isElasticVersionPresent());
    }

    @Test
    public void idMustBePresentAndNotBlank() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.NONE),
                                                            Map.of("id", new IdDecorator()));

        assertInstanceOf(IllegalArgumentException.class, fail(processor, "{\"id\":\"\",\"make\":\"Audi\"}", context(TENANT1)));
        assertInstanceOf(IllegalArgumentException.class, fail(processor, "{\"id\":null,\"make\":\"Audi\"}", context(TENANT1)));
        assertInstanceOf(IllegalArgumentException.class, fail(processor, "{\"make\":\"Audi\"}", context(TENANT1)));
    }

    @Test
    public void autoGeneratedIdIsAssignedWhenBlankAndKeptWhenGiven() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.NONE),
                                                            Map.of("id", new AutoGeneratedIdDecorator()));

        EntityHolder<RawJson> generated = process(processor, "{\"id\":null,\"make\":\"Audi\"}", context(TENANT1));
        assertEquals(generated.id(), json(generated.entity()).get("id").asString(), "The generated id is written into the data");
        UUID.fromString(generated.id());

        EntityHolder<RawJson> blank = process(processor, "{\"id\":\"\",\"make\":\"Audi\"}", context(TENANT1));
        UUID.fromString(blank.id());

        EntityHolder<RawJson> given = process(processor, "{\"id\":\"given-1\",\"make\":\"Audi\"}", context(TENANT1));
        assertEquals("given-1", given.id());
        assertEquals("given-1", json(given.entity()).get("id").asString());

        assertInstanceOf(IllegalArgumentException.class,
                         fail(processor, "{\"make\":\"Audi\"}", context(TENANT1)),
                         "The id field must be present for an id to be generated");
    }

    @Test
    public void versionIsExtractedAndNotPersisted() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.NONE).versionFieldName("version").build(),
                                                            Map.of("id", new IdDecorator(), "version", new VersionDecorator()));

        EntityHolder<RawJson> versioned = process(processor, "{\"id\":\"car-1\",\"version\":\"3:7\",\"make\":\"Audi\"}", context(TENANT1));
        assertEquals(json("{\"id\":\"car-1\",\"make\":\"Audi\"}"), json(versioned.entity()), "The version field is not written to the document");
        assertEquals("3:7", versioned.version());
        assertTrue(versioned.isElasticVersionPresent());
        assertEquals(new ElasticVersion(3L, 7L), versioned.getElasticVersionIfPresent());

        EntityHolder<RawJson> initial = process(processor, "{\"id\":\"car-1\",\"version\":null,\"make\":\"Audi\"}", context(TENANT1));
        assertNull(initial.version());
        assertFalse(initial.isElasticVersionPresent());
        assertNull(initial.getElasticVersionIfPresent());

        EntityHolder<RawJson> empty = process(processor, "{\"id\":\"car-1\",\"version\":\"\",\"make\":\"Audi\"}", context(TENANT1));
        assertFalse(empty.isElasticVersionPresent(), "An empty version is the same as none");

        EntityHolder<RawJson> absent = process(processor, "{\"id\":\"car-1\",\"make\":\"Audi\"}", context(TENANT1));
        assertFalse(absent.isElasticVersionPresent());

        EntityHolder<RawJson> malformed = process(processor, "{\"id\":\"car-1\",\"version\":\"7\",\"make\":\"Audi\"}", context(TENANT1));
        assertThrows(IllegalArgumentException.class, malformed::getElasticVersionIfPresent);
    }

    @Test
    public void sharedTenancyWithoutATenantFieldTakesTheTenantFromTheParticipant() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.SHARED),
                                                            Map.of("id", new IdDecorator()));

        EntityHolder<RawJson> injected = process(processor, "{\"id\":\"car-1\",\"make\":\"Audi\"}", context(TENANT1));
        assertEquals(json("{\"id\":\"car-1\",\"make\":\"Audi\",\"tenantId\":\"tenant1\"}"), json(injected.entity()),
                     "The participant's tenant is written into the document under the configured field name");
        assertEquals("tenant1", injected.tenantId());
        assertEquals("tenant1-car-1", injected.getDocumentId(), "A shared document id is prefixed with the tenant");
        assertEquals(MultiTenancyType.SHARED, injected.multiTenancyType());

        EntityHolder<RawJson> matching = process(processor, "{\"id\":\"car-1\",\"tenantId\":\"tenant1\",\"make\":\"Audi\"}", context(TENANT1));
        assertEquals("tenant1", json(matching.entity()).get("tenantId").asString());
        assertEquals("tenant1", matching.tenantId());

        EntityHolder<RawJson> nullValued = process(processor, "{\"id\":\"car-1\",\"tenantId\":null,\"make\":\"Audi\"}", context(TENANT1));
        assertEquals("tenant1", json(nullValued.entity()).get("tenantId").asString(), "A null tenant is replaced by the participant's");
        assertEquals("tenant1", nullValued.tenantId());

        assertInstanceOf(IllegalArgumentException.class,
                         fail(processor, "{\"id\":\"car-1\",\"tenantId\":\"tenant2\",\"make\":\"Audi\"}", context(TENANT1)),
                         "Another tenant's id is rejected");

        assertInstanceOf(IllegalStateException.class,
                         fail(processor, "{\"id\":\"car-1\",\"make\":\"Audi\"}", context(ORGANIZATION)),
                         "A participant without a tenant cannot write a shared entity that has no tenant field");

        EntityContext context = context(TENANT1);
        process(processor, "{\"id\":\"car-1\",\"make\":\"Audi\"}", context);
        assertFalse(context.hasTenantSelection(), "Without a tenant field the context's selection is left alone");
    }

    @Test
    public void tenantIdFieldIsOwnedByATenantedParticipant() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.SHARED).tenantIdFieldName("tenantId").build(),
                                                            Map.of("id", new IdDecorator(), "tenantId", new TenantIdDecorator()));

        EntityHolder<RawJson> filled = process(processor, "{\"id\":\"car-1\",\"tenantId\":\"\",\"make\":\"Audi\"}", context(TENANT1));
        assertEquals("tenant1", json(filled.entity()).get("tenantId").asString(), "A blank tenant id is filled with the participant's tenant");
        assertEquals("tenant1", filled.tenantId());
        assertEquals("tenant1-car-1", filled.getDocumentId());

        EntityHolder<RawJson> own = process(processor, "{\"id\":\"car-1\",\"tenantId\":\"tenant1\",\"make\":\"Audi\"}", context(TENANT1));
        assertEquals("tenant1", own.tenantId());

        assertInstanceOf(IllegalArgumentException.class,
                         fail(processor, "{\"id\":\"car-1\",\"tenantId\":\"tenant2\",\"make\":\"Audi\"}", context(TENANT1)),
                         "Another tenant's id is rejected");

        EntityHolder<RawJson> nullValued = process(processor, "{\"id\":\"car-1\",\"tenantId\":null,\"make\":\"Audi\"}", context(TENANT1));
        assertEquals("tenant1", json(nullValued.entity()).get("tenantId").asString(), "A null tenant id is filled like a blank one");
        assertEquals("tenant1", nullValued.tenantId());

        assertInstanceOf(IllegalArgumentException.class,
                         fail(processor, "{\"id\":\"car-1\",\"make\":\"Audi\"}", context(TENANT1)),
                         "The tenant id field must be present");
    }

    @Test
    public void tenantIdFieldIsNamedThroughTheDataByAnOrganizationParticipant() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.SHARED).tenantIdFieldName("tenantId").build(),
                                                            Map.of("id", new IdDecorator(), "tenantId", new TenantIdDecorator()));

        EntityContext context = context(ORGANIZATION);
        EntityHolder<RawJson> named = process(processor, "{\"id\":\"car-1\",\"tenantId\":\"tenant2\",\"make\":\"Audi\"}", context);
        assertEquals("tenant2", named.tenantId());
        assertEquals("tenant2-car-1", named.getDocumentId());
        assertEquals(List.of("tenant2"), context.getTenantSelection(), "The tenant the data names becomes the context's selection");

        assertInstanceOf(IllegalArgumentException.class,
                         fail(processor, "{\"id\":\"car-1\",\"tenantId\":\"\",\"make\":\"Audi\"}", context(ORGANIZATION)),
                         "Without a tenant of its own the data must name one");

        EntityContext stale = context(ORGANIZATION).setTenantSelection(List.of("stale"));
        List<EntityHolder<RawJson>> holders = processArray(processor,
                                                          "[{\"id\":\"a\",\"tenantId\":\"tenant2\"},{\"id\":\"b\",\"tenantId\":\"tenant1\"},{\"id\":\"c\",\"tenantId\":\"tenant2\"}]",
                                                          stale);
        assertEquals(List.of("tenant2", "tenant1", "tenant2"),
                     stale.getTenantSelection(),
                     "A bulk write replaces the selection with one entry per entity, in data order");
        assertEquals(List.of("tenant2-a", "tenant1-b", "tenant2-c"), holders.stream().map(EntityHolder::getDocumentId).toList());
    }

    @Test
    public void timeReferenceIsDuplicatedIntoTheTimestampField() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.NONE).timeReferenceFieldName("occurred").build(),
                                                            Map.of("id", new IdDecorator(), "occurred", new TimeReferenceDecorator()));

        JsonNode written = json(process(processor, "{\"id\":\"alert-1\",\"occurred\":1700000000000,\"level\":\"high\"}", context(TENANT1)).entity());
        assertTrue(written.has("@timestamp"), "Elasticsearch's @timestamp field is added");
        assertEquals(written.get("occurred"), written.get("@timestamp"), "@timestamp carries the time reference's value");
        assertEquals("high", written.get("level").asString());

        JsonNode nulled = json(process(processor, "{\"id\":\"alert-1\",\"occurred\":null}", context(TENANT1)).entity());
        assertTrue(nulled.has("@timestamp"));
        assertTrue(nulled.get("@timestamp").isNull());
    }

    @Test
    public void arrayInputYieldsOneHolderPerElement() {
        TokenBufferUpsertPreProcessor processor = processor(descriptor(MultiTenancyType.SHARED),
                                                            Map.of("id", new IdDecorator()));
        String input = """
                [{"id":"a","n":1,"tags":["x"],"owner":{"id":"p"}},{"id":"b","n":2},{"id":"c","n":3,"nested":[[1,2],[3]]}]""";

        List<EntityHolder<RawJson>> holders = processArray(processor, input, context(TENANT1));

        assertEquals(List.of("a", "b", "c"), holders.stream().map(EntityHolder::id).toList());
        assertEquals(json("{\"id\":\"a\",\"n\":1,\"tags\":[\"x\"],\"owner\":{\"id\":\"p\"},\"tenantId\":\"tenant1\"}"), json(holders.get(0).entity()));
        assertEquals(json("{\"id\":\"b\",\"n\":2,\"tenantId\":\"tenant1\"}"), json(holders.get(1).entity()));
        assertEquals(json("{\"id\":\"c\",\"n\":3,\"nested\":[[1,2],[3]],\"tenantId\":\"tenant1\"}"), json(holders.get(2).entity()));

        assertEquals(List.of(), processArray(processor, "[]", context(TENANT1)), "An empty array yields nothing");

        assertInstanceOf(IllegalArgumentException.class,
                         fail(processor, "[{\"id\":\"a\"},{\"id\":\"\"}]", context(TENANT1)),
                         "One bad element fails the whole array");

        Future<EntityHolder<RawJson>> single = processor.process(buffer("[{\"id\":\"a\"},{\"id\":\"b\"}]"), context(TENANT1));
        assertTrue(single.failed(), "An array is not a single entity");
        assertInstanceOf(IllegalStateException.class, single.cause());
    }

    // ---- fixtures ----

    private static ScopedParticipant applicationParticipant(String tenantId) {
        return new DefaultApplicationParticipant("user-" + tenantId,
                                                 ORG,
                                                 APP,
                                                 tenantId,
                                                 Map.of(ParticipantConstants.PARTICIPANT_TYPE_METADATA_KEY,
                                                        ParticipantConstants.PARTICIPANT_TYPE_USER),
                                                 List.of("USER"));
    }

    private static EntityContext context(ScopedParticipant participant) {
        return new DefaultEntityContext(participant);
    }

    private static EntityDescriptor.EntityDescriptorBuilder descriptor(MultiTenancyType multiTenancyType) {
        return EntityDescriptor.builder()
                               .id(ORG + "." + APP + ".car")
                               .organizationId(ORG)
                               .applicationId(APP)
                               .name("Car")
                               .itemIndex("struct_car")
                               .idFieldName("id")
                               .multiTenancyType(multiTenancyType);
    }

    private TokenBufferUpsertPreProcessor processor(EntityDescriptor.EntityDescriptorBuilder descriptor,
                                                    Map<String, C3Decorator> decoratedPaths) {
        return processor(descriptor.build(), decoratedPaths);
    }

    /**
     * Wires each decorated json path to the real field processor that handles its decorator, as
     * {@code EntityServiceCache} does from an {@code EntityDefinition}'s decorated properties.
     */
    @SuppressWarnings("unchecked")
    private TokenBufferUpsertPreProcessor processor(EntityDescriptor descriptor, Map<String, C3Decorator> decoratedPaths) {
        Map<String, UpsertFieldPreProcessor<?, ?, ?>> fieldProcessors = new LinkedHashMap<>();
        for (UpsertFieldPreProcessor<?, ?, ?> fieldProcessor : List.of(new IdUpsertFieldPreProcessor(),
                                                                         new AutoGeneratedIdUpsertFieldPreProcessor(),
                                                                         new VersionUpsertFieldPreProcessor(),
                                                                         new TenantIdUpsertFieldPreProcessor(),
                                                                         new TimeRefUpsertFieldPreProcessor())) {
            fieldProcessors.put(fieldProcessor.implementsDecorator().getName(), fieldProcessor);
        }
        Map<String, DecoratorLogic> logic = new LinkedHashMap<>();
        decoratedPaths.forEach((path, decorator) -> logic.put(path, new DecoratorLogic(decorator,
                                                                                       (UpsertFieldPreProcessor<C3Decorator, Object, Object>) fieldProcessors.get(decorator.getClass().getName()))));
        return new TokenBufferUpsertPreProcessor(properties, jsonMapper, descriptor, logic);
    }

    private TokenBuffer buffer(String json) {
        TokenBuffer buffer = new TokenBuffer(jsonMapper._serializationContext(), false);
        buffer.writePOJO(jsonMapper.readTree(json));
        return buffer;
    }

    private JsonNode json(String json) {
        return jsonMapper.readTree(json);
    }

    private JsonNode json(RawJson rawJson) {
        return jsonMapper.readTree(rawJson.data());
    }

    // The processing completes synchronously, so a result or cause is available as soon as the call returns
    private EntityHolder<RawJson> process(TokenBufferUpsertPreProcessor processor, String json, EntityContext context) {
        Future<EntityHolder<RawJson>> future = processor.process(buffer(json), context);
        assertTrue(future.succeeded(), () -> "Expected success but failed with: " + future.cause());
        return future.result();
    }

    private List<EntityHolder<RawJson>> processArray(TokenBufferUpsertPreProcessor processor, String json, EntityContext context) {
        Future<List<EntityHolder<RawJson>>> future = processor.processArray(buffer(json), context);
        assertTrue(future.succeeded(), () -> "Expected success but failed with: " + future.cause());
        return future.result();
    }

    private Throwable fail(TokenBufferUpsertPreProcessor processor, String json, EntityContext context) {
        Future<?> future = json.startsWith("[")
                ? processor.processArray(buffer(json), context)
                : processor.process(buffer(json), context);
        assertTrue(future.failed(), () -> "Expected a failure but got: " + future.result());
        return future.cause();
    }
}
